// Builds modules/schemas.js: the shape of every collector's output, inferred
// from all real captures in tests/fixtures (live pages) and
// tests/fixtures/captured (local test pages, see capture-collector-outputs.mjs).
//
//   npm run build:schemas
//
// A unit test fails when modules/schemas.js and the fixtures disagree, so add a
// capture and rebuild whenever a collector starts returning something new.
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { inferSchema, allowNull } from '../modules/conform.js';

const FIXTURES = new URL('../tests/fixtures/', import.meta.url);
const SECTIONS = ['head', 'body', 'health', 'signals', 'network', 'rendering'];

// Fields the collectors set to null on purpose (read from the collector code),
// even when no capture happens to show it.
const NULLABLE = {
  // phase2-network.js rounds every timing/size with a helper that returns null,
  // and leaves whole blocks null when a fetch fails
  network: (s, path) => s.t === 'num' || ['nav', 'doc', 'resources', 'robots', 'llms', 'sitemap', 'sitemap.lastmod'].includes(path),
  // phase3-rendering.js: optional blocks and meta values (null = tag missing)
  rendering: (s, path) => ['mount', 'facts', 'links', 'mount.renderedWords', 'raw.status', 'panels[].inRaw'].includes(path) || /^meta\.(raw|rendered)\./.test(path),
  // phase1-elements.js: review count is null when the page shows none
  signals: (s, path) => /(^|\.)reviewCount$/.test(path),
  body: (s, path) => /(^|\.)reviewCount$/.test(path),
};

function captures(section) {
  const top = readdirSync(FIXTURES).filter((f) => f.endsWith(`-${section}.json`)).map((f) => new URL(f, FIXTURES));
  const cap = readdirSync(new URL('captured/', FIXTURES)).filter((f) => f.endsWith(`-${section}.json`)).map((f) => new URL(`captured/${f}`, FIXTURES));
  return [...top, ...cap].map((u) => JSON.parse(readFileSync(u, 'utf8')));
}

export function buildSchemas() {
  const out = {};
  SECTIONS.forEach((section) => {
    const schema = inferSchema(captures(section));
    out[section] = NULLABLE[section] ? allowNull(schema, NULLABLE[section]) : schema;
  });
  return out;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const schemas = buildSchemas();
  const target = new URL('../modules/schemas.js', import.meta.url);
  writeFileSync(target, `// Generated by scripts/build-schemas.mjs from real collector captures. Do not edit by hand.\n// The shape of each collector's output, used by conform() before the rules run.\n\nexport const SCHEMAS = ${JSON.stringify(schemas)};\n`);
  console.log(`wrote ${fileURLToPath(target)} (${Object.keys(schemas).join(', ')})`);
}
